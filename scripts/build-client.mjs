/**
 * Build the Web client half of the plugin.
 *
 * The browser module table expects `window.__ModuleLoader__.load({ id, factory })`
 * where `factory(require)` returns the module exports. esbuild's CJS output
 * assigns to `exports`, so this script wraps it in a module shim and returns
 * `module.exports`; `react` stays external because the module table provides it.
 */
import { build } from 'esbuild'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const manifest = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'))

const bundle = await build({
  entryPoints: [join(root, 'src/client/index.ts')],
  bundle: true,
  write: false,
  format: 'cjs',
  platform: 'browser',
  target: 'es2022',
  external: ['react'],
  legalComments: 'none',
  logLevel: 'warning',
})

const code = (bundle.outputFiles?.[0]?.text ?? '').replace(/^"use strict";\n/, '')
const output = `// Generated by scripts/build-client.mjs -- do not edit.
window.__ModuleLoader__.load({
  id: ${JSON.stringify(manifest.name)},
  factory(require) {
    var module = { exports: {} };
    var exports = module.exports;
${code}
    return module.exports;
  },
});
`

await mkdir(join(root, 'lib'), { recursive: true })
await writeFile(join(root, 'lib/client.js'), output)
process.stdout.write(`built lib/client.js (${String(output.length)} bytes)\n`)